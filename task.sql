CREATE DATABASE ShopDB;
USE ShopDB; 


CREATE TABLE Countries (
    ID INT AUTO_INCREMENT,
    Name VARCHAR(50),
    PRIMARY KEY (ID)
) ENGINE=InnoDB;

CREATE TABLE GeoIPCache (
    ID INT AUTO_INCREMENT,
    PRIMARY KEY (ID),
    IPRange VARCHAR(30),
    CountryID INT
) ENGINE=Memory;

CREATE TABLE ProductDescription (
	ID INT AUTO_INCREMENT,
	PRIMARY KEY (ID),
	Description VARCHAR(100),
	ProductID INT,
	CountryID INT
) ENGINE=MyISAM;

CREATE TABLE Logs (
	ID INT AUTO_INCREMENT,
	PRIMARY KEY (ID),
	Timestamp Timestamp,
	Message VARCHAR(256)
) ENGINE=BLACKHOLE;

CREATE TABLE ProductReporting (
	Date DATE NOT NULL,
	ProductName VARCHAR(50) NOT NULL,
	Orders INT NOT NULL
) ENGINE=CSV;

